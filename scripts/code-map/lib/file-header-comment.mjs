/**
 * Extract leading file-level documentation from source text.
 * Supports JSDoc, C#/Rust line docs, Python module strings, and more.
 */

/**
 * @param {string} line
 * @returns {boolean}
 */
function isSkippableDirectiveLine(line) {
  const trimmed = line.trim();
  return (
    trimmed === '' ||
    trimmed === "'use strict';" ||
    trimmed === '"use strict";' ||
    trimmed.startsWith('// @ts-') ||
    trimmed.startsWith('/* eslint') ||
    trimmed.startsWith('// eslint') ||
    trimmed.startsWith('// @ts-nocheck') ||
    trimmed.startsWith('#nullable') ||
    trimmed.startsWith('#pragma') ||
    trimmed.startsWith('#region') ||
    trimmed.startsWith('#endregion') ||
    trimmed === '#!/usr/bin/env python' ||
    /^#\s*-\*-/.test(trimmed) ||
    /^\/\/\s*<auto-generated/.test(trimmed)
  );
}

/**
 * @param {string} raw
 * @returns {string}
 */
function cleanBlockComment(raw) {
  const lines = raw
    .replace(/^\/\*\*/, '')
    .replace(/\*\/$/, '')
    .split(/\r?\n/)
    .map((line) => line.replace(/^\s*\*?\s?/, '').trimEnd());

  while (lines.length > 0 && lines[0].trim() === '') {
    lines.shift();
  }
  while (lines.length > 0 && lines[lines.length - 1].trim() === '') {
    lines.pop();
  }

  return lines.join('\n').trim();
}

/**
 * @param {string} opener
 * @param {string} text
 * @param {number} offset
 * @returns {string | null}
 */
function readTripleQuotedString(opener, text, offset) {
  if (!text.slice(offset).startsWith(opener)) {
    return null;
  }
  let pos = offset + opener.length;
  while (pos < text.length) {
    const idx = text.indexOf(opener, pos);
    if (idx === -1) {
      return null;
    }
    if (text[idx - 1] !== '\\') {
      return text.slice(offset + opener.length, idx).trim();
    }
    pos = idx + opener.length;
  }
  return null;
}

/**
 * @param {string} text
 * @param {number} offset
 * @returns {string | null}
 */
function readLineCommentBlock(text, offset, linePrefix) {
  const lines = [];
  let pos = offset;
  const prefixPattern =
    linePrefix === '//!'
      ? /^\s*\/\/!\s?(.*)$/
      : linePrefix === '///'
        ? /^\s*\/\/\/\s?(.*)$/
        : /^\s*\/\/\s?(.*)$/;

  while (pos < text.length) {
    const lineEnd = text.indexOf('\n', pos);
    const lineEndPos = lineEnd === -1 ? text.length : lineEnd;
    const line = text.slice(pos, lineEndPos);
    const trimmed = line.trim();

    if (trimmed === '') {
      pos = lineEndPos + (lineEnd === -1 ? 0 : 1);
      continue;
    }

    const match = line.match(prefixPattern);
    if (match) {
      lines.push(match[1] ?? '');
      pos = lineEndPos + (lineEnd === -1 ? 0 : 1);
      continue;
    }
    break;
  }

  return lines.length > 0 ? lines.join('\n').trim() : null;
}

/**
 * @param {string} content
 * @returns {string | null}
 */
export function extractFileHeaderComment(content) {
  // Line comments are matched with `(.*)$`, and `.` never matches `\r`, so a
  // CRLF file would lose every `//`, `///`, and `//!` header. Normalize line
  // endings once so every reader below sees LF-only text.
  let text = content.replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n');
  let offset = 0;

  if (text.startsWith('#!')) {
    const newline = text.indexOf('\n');
    offset = newline === -1 ? text.length : newline + 1;
  }

  while (offset < text.length) {
    const lineEnd = text.indexOf('\n', offset);
    const lineEndPos = lineEnd === -1 ? text.length : lineEnd;
    const line = text.slice(offset, lineEndPos);
    if (!isSkippableDirectiveLine(line)) {
      break;
    }
    offset = lineEndPos + (lineEnd === -1 ? 0 : 1);
  }

  const rest = text.slice(offset);

  if (rest.startsWith('/**')) {
    const end = rest.indexOf('*/');
    if (end !== -1) {
      return cleanBlockComment(rest.slice(0, end + 2));
    }
    return null;
  }

  for (const opener of ['"""', "'''"]) {
    const doc = readTripleQuotedString(opener, text, offset);
    if (doc) {
      return doc;
    }
  }

  if (rest.startsWith('//!')) {
    return readLineCommentBlock(text, offset, '//!');
  }

  if (rest.startsWith('///')) {
    return readLineCommentBlock(text, offset, '///');
  }

  if (/^\s*\/\//.test(rest)) {
    return readLineCommentBlock(text, offset, '//');
  }

  return null;
}
